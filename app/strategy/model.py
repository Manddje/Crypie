"""Strategy configuration: which indicators to compute and when to buy or sell.

A strategy is plain JSON so it can be edited by hand, generated by Claude, stored in the
``settings`` table and backtested. Example::

    {
      "name": "RSI mean reversion",
      "market": "BTC-EUR",
      "interval": "1h",
      "indicators": [
        {"id": "rsi14", "type": "rsi", "period": 14},
        {"id": "ema50", "type": "ema", "period": 50}
      ],
      "buy": [
        {"left": "rsi14", "op": "<", "right": 30},
        {"left": "close", "op": ">", "right": "ema50"}
      ],
      "sell": [{"left": "rsi14", "op": ">", "right": 70}],
      "stop_loss_pct": 5,
      "take_profit_pct": null,
      "position_size_pct": 100
    }
"""

from __future__ import annotations

import re
from typing import Annotated, Literal

from pydantic import BaseModel, Field, field_validator, model_validator

INTERVALS = ("1m", "5m", "15m", "30m", "1h", "2h", "4h", "6h", "8h", "12h", "1d")
Operator = Literal["<", "<=", ">", ">=", "crosses_above", "crosses_below"]
IdStr = Annotated[str, Field(pattern=r"^[a-z][a-z0-9_]{0,31}$")]


class SmaSpec(BaseModel):
    type: Literal["sma"]
    id: IdStr
    period: int = Field(ge=2, le=500)


class EmaSpec(BaseModel):
    type: Literal["ema"]
    id: IdStr
    period: int = Field(ge=2, le=500)


class RsiSpec(BaseModel):
    type: Literal["rsi"]
    id: IdStr
    period: int = Field(default=14, ge=2, le=200)


class MacdSpec(BaseModel):
    """Exposes three series: ``<id>``, ``<id>_signal`` and ``<id>_hist``."""

    type: Literal["macd"]
    id: IdStr
    fast: int = Field(default=12, ge=2, le=200)
    slow: int = Field(default=26, ge=3, le=500)
    signal: int = Field(default=9, ge=2, le=200)

    @model_validator(mode="after")
    def _fast_before_slow(self) -> MacdSpec:
        if self.fast >= self.slow:
            raise ValueError("macd fast period must be smaller than slow period")
        return self


class BollingerSpec(BaseModel):
    """Exposes three series: ``<id>_upper``, ``<id>_middle`` and ``<id>_lower``."""

    type: Literal["bollinger"]
    id: IdStr
    period: int = Field(default=20, ge=2, le=500)
    std_dev: float = Field(default=2.0, gt=0, le=5)


IndicatorSpec = Annotated[
    SmaSpec | EmaSpec | RsiSpec | MacdSpec | BollingerSpec, Field(discriminator="type")
]

PRICE_FIELDS = ("open", "high", "low", "close", "volume")


class Condition(BaseModel):
    """``left op right``; both sides are a series name or (right only) a number."""

    left: str
    op: Operator
    right: str | float

    @field_validator("left")
    @classmethod
    def _left_is_series(cls, v: str) -> str:
        if not re.fullmatch(r"[a-z][a-z0-9_]*", v):
            raise ValueError(f"left must be a series name, got {v!r}")
        return v


class Strategy(BaseModel):
    name: str = Field(min_length=1, max_length=80)
    description: str = ""
    market: str = Field(pattern=r"^[A-Z0-9]{2,10}-EUR$")
    interval: Literal[INTERVALS] = "1h"  # type: ignore[valid-type]
    indicators: list[IndicatorSpec] = Field(min_length=1, max_length=10)
    buy: list[Condition] = Field(min_length=1, max_length=8, description="ALL must hold")
    sell: list[Condition] = Field(min_length=1, max_length=8, description="ALL must hold")
    stop_loss_pct: float | None = Field(default=None, gt=0, le=50)
    take_profit_pct: float | None = Field(default=None, gt=0, le=500)
    position_size_pct: float = Field(default=100, gt=0, le=100)

    def series_names(self) -> set[str]:
        names = set(PRICE_FIELDS)
        for ind in self.indicators:
            if ind.type == "macd":
                names.update({ind.id, f"{ind.id}_signal", f"{ind.id}_hist"})
            elif ind.type == "bollinger":
                names.update({f"{ind.id}_upper", f"{ind.id}_middle", f"{ind.id}_lower"})
            else:
                names.add(ind.id)
        return names

    @model_validator(mode="after")
    def _references_resolve(self) -> Strategy:
        ids = [i.id for i in self.indicators]
        if len(ids) != len(set(ids)):
            raise ValueError("indicator ids must be unique")
        names = self.series_names()
        for cond in self.buy + self.sell:
            for side in (cond.left, cond.right):
                if isinstance(side, str) and side not in names:
                    raise ValueError(
                        f"unknown series {side!r}; available: {', '.join(sorted(names))}"
                    )
        return self


DEFAULT_STRATEGY = Strategy(
    name="RSI mean reversion",
    description="Koop als RSI onder 30 duikt terwijl de koers boven de EMA50 ligt; "
    "verkoop als RSI boven 70 komt. Stop-loss 5%.",
    market="BTC-EUR",
    interval="1h",
    indicators=[
        RsiSpec(type="rsi", id="rsi14", period=14),
        EmaSpec(type="ema", id="ema50", period=50),
    ],
    buy=[
        Condition(left="rsi14", op="<", right=30),
        Condition(left="close", op=">", right="ema50"),
    ],
    sell=[Condition(left="rsi14", op=">", right=70)],
    stop_loss_pct=5,
)
